package org.group_three.constants.enums;


/**
 * This enum allows for Stylisation of Lists as Record-Components
 * @author Luca
 * @see org.group_three.debug.annotations.PrintStyle
 * */
public enum ValueStyle {
    ///  as one value
    VALUE,
    /// each entry as its own column
    COLUMN,
    /// the list as a whole in the column
    LIST
}
